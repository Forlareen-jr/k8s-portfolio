import os
import time

import psycopg
from flask import Flask, jsonify, request
from psycopg.rows import dict_row

app = Flask(__name__)


def get_db_connection():
    return psycopg.connect(
        host=os.getenv("DB_HOST", "postgres"),
        port=os.getenv("DB_PORT", "5432"),
        dbname=os.environ["DB_NAME"],
        user=os.environ["DB_USERNAME"],
        password=os.environ["DB_PASSWORD"],
        row_factory=dict_row,
    )


def initialize_database():
    """Wait for PostgreSQL and create the tickets table if needed."""
    for attempt in range(30):
        try:
            with get_db_connection() as conn:
                with conn.cursor() as cur:
                    cur.execute("""
                        CREATE TABLE IF NOT EXISTS tickets (
                            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            title VARCHAR(200) NOT NULL,
                            description TEXT NOT NULL DEFAULT '',
                            category VARCHAR(100) NOT NULL,
                            priority VARCHAR(20) NOT NULL DEFAULT 'Medium',
                            status VARCHAR(30) NOT NULL DEFAULT 'Open',
                            created_by VARCHAR(100) NOT NULL,
                            assigned_to VARCHAR(100)
                        )
                    """)

                    cur.execute("""
                        INSERT INTO tickets
                            (id, title, description, category, priority,
                             status, created_by, assigned_to)
                        VALUES
                            (1042, 'Laptop cannot connect to Wi-Fi',
                             'Unable to connect to the office Wi-Fi network.',
                             'Network', 'High', 'Open', 'John', 'IT Support')
                        ON CONFLICT (id) DO NOTHING
                    """)

                    # Ensure automatically generated IDs continue above
                    # the sample ticket ID.
                    cur.execute("""
                        SELECT setval(
                            pg_get_serial_sequence('tickets', 'id'),
                            GREATEST(COALESCE((SELECT MAX(id) FROM tickets), 1), 1),
                            EXISTS (SELECT 1 FROM tickets)
                        )
                    """)

            print("Database initialized successfully.")
            return

        except psycopg.OperationalError as exc:
            print(f"Waiting for PostgreSQL ({attempt + 1}/30): {exc}")
            time.sleep(2)

    raise RuntimeError("Could not connect to PostgreSQL after repeated attempts.")


@app.get("/health")
def health():
    try:
        with get_db_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT 1")

        return jsonify({
            "status": "healthy",
            "service": "helpdesk-backend",
            "database": "connected",
        })

    except psycopg.Error:
        return jsonify({
            "status": "unhealthy",
            "database": "disconnected",
        }), 503


@app.get("/tickets")
def get_tickets():
    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT * FROM tickets ORDER BY id")
            tickets = cur.fetchall()

    return jsonify(tickets)


@app.post("/tickets")
def create_ticket():
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({"error": "A JSON request body is required."}), 400

    required_fields = ["title", "category", "created_by"]
    missing_fields = [
        field for field in required_fields
        if not isinstance(data.get(field), str) or not data[field].strip()
    ]

    if missing_fields:
        return jsonify({
            "error": "Required fields are missing.",
            "fields": missing_fields,
        }), 400

    priority = data.get("priority", "Medium")
    allowed_priorities = {"Low", "Medium", "High", "Critical"}

    if priority not in allowed_priorities:
        return jsonify({
            "error": "Priority must be Low, Medium, High, or Critical."
        }), 400

    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO tickets
                    (title, description, category, priority, status, created_by)
                VALUES (%s, %s, %s, %s, 'Open', %s)
                RETURNING *
            """, (
                data["title"].strip(),
                data.get("description", ""),
                data["category"].strip(),
                priority,
                data["created_by"].strip(),
            ))

            ticket = cur.fetchone()

    return jsonify(ticket), 201


@app.patch("/tickets/<int:ticket_id>/status")
def update_ticket_status(ticket_id):
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({"error": "A JSON request body is required."}), 400

    new_status = data.get("status")
    allowed_statuses = {"Open", "In Progress", "Resolved", "Closed"}

    if new_status not in allowed_statuses:
        return jsonify({
            "error": "Status must be Open, In Progress, Resolved, or Closed."
        }), 400

    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                UPDATE tickets
                SET status = %s
                WHERE id = %s
                RETURNING *
            """, (new_status, ticket_id))

            ticket = cur.fetchone()

    if ticket is None:
        return jsonify({"error": "Ticket not found."}), 404

    return jsonify(ticket)


if __name__ == "__main__":
    initialize_database()
    app.run(host="0.0.0.0", port=8080)
